#!/usr/bin/env node
/**
 * Generates worker/integrations/opengrants/client.gen.ts from the committed
 * OpenAPI spec (CLAUDE.md: "the client is generated from the committed
 * OpenAPI spec"; never invent endpoints). Only operations in the spec exist
 * in the client. Responses without a schema in the spec are typed `unknown`
 * and interpreted in mapping.ts.
 *
 *   node scripts/gen-opengrants.mjs          write the file
 *   node scripts/gen-opengrants.mjs --check  exit 1 if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const specPath = fileURLToPath(new URL('worker/integrations/opengrants/openapi.json', root));
const outPath = fileURLToPath(new URL('worker/integrations/opengrants/client.gen.ts', root));

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const quote = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));

/** OpenAPI schema → TypeScript type (the subset the spec uses). */
function tsType(schema, indent = '') {
  if (!schema) return 'unknown';
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  const nullable = schema.nullable ? ' | null' : '';
  switch (schema.type) {
    case 'string':
      return `string${nullable}`;
    case 'integer':
    case 'number':
      return `number${nullable}`;
    case 'boolean':
      return `boolean${nullable}`;
    case 'array':
      return `${wrap(tsType(schema.items, indent))}[]${nullable}`;
    case 'object': {
      const props = schema.properties ?? {};
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = Object.entries(props).map(([k, v]) => {
        const doc = v.description ? `${inner}/** ${v.description.replace(/\*\//g, '*\\/')} */\n` : '';
        return `${doc}${inner}${quote(k)}${required.has(k) ? '' : '?'}: ${tsType(v, inner)};`;
      });
      return lines.length ? `{\n${lines.join('\n')}\n${indent}}${nullable}` : `Record<string, unknown>${nullable}`;
    }
    default:
      return 'unknown';
  }
}

const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

export function generate(spec) {
  const out = [];
  out.push('// Generated by scripts/gen-opengrants.mjs from openapi.json. Do not edit by hand.');
  out.push(`// ${spec.info.title} ${spec.info.version}`);
  out.push('');
  out.push(`export const OPENGRANTS_BASE_URL = ${JSON.stringify(spec.servers[0].url)};`);
  out.push('');
  out.push('export interface OpenGrantsHttp {');
  out.push('  request(method: string, path: string, query: Record<string, string | number | boolean | undefined>, body?: unknown): Promise<unknown>;');
  out.push('}');
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(item)) {
      const name = op.operationId;
      if (!name) throw new Error(`${method} ${path} has no operationId`);
      const T = pascal(name);
      const params = op.parameters ?? [];
      const query = params.filter((p) => p.in === 'query');
      const pathParams = params.filter((p) => p.in === 'path');
      out.push('');
      out.push(`/** ${method.toUpperCase()} ${path}${op.summary ? ` — ${op.summary}` : ''} */`);
      if (query.length) {
        out.push(`export interface ${T}Query {`);
        for (const p of query) {
          const doc = [p.description, p.deprecated ? '@deprecated' : null].filter(Boolean).join(' ');
          if (doc) out.push(`  /** ${doc.replace(/\*\//g, '*\\/')} */`);
          out.push(`  ${quote(p.name)}${p.required ? '' : '?'}: ${tsType(p.schema, '  ')};`);
        }
        out.push('}');
      }
      const body = op.requestBody?.content?.['application/json']?.schema;
      if (body) out.push(`export type ${T}Body = ${tsType(body)};`);
      const ok = op.responses?.['200']?.content?.['application/json']?.schema;
      out.push(`export type ${T}Response = ${ok ? tsType(ok) : 'unknown'};`);
      const args = [
        'http: OpenGrantsHttp',
        ...pathParams.map((p) => `${p.name}: string`),
        ...(query.length ? [`query: ${T}Query = {}`] : []),
        ...(body ? [`body: ${T}Body`] : []),
      ];
      const pathExpr = '`' + path.replace(/\{(\w+)\}/g, (_, n) => '${encodeURIComponent(' + n + ')}') + '`';
      out.push(`export function ${name}(${args.join(', ')}): Promise<${T}Response> {`);
      out.push(
        `  return http.request(${JSON.stringify(method.toUpperCase())}, ${pathExpr}, ${query.length ? 'query as Record<string, string | number | boolean | undefined>' : '{}'}${body ? ', body' : ''}) as Promise<${T}Response>;`,
      );
      out.push('}');
    }
  }
  return `${out.join('\n')}\n`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const code = generate(JSON.parse(readFileSync(specPath, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = readFileSync(outPath, 'utf8');
    if (current !== code) {
      console.error('client.gen.ts is out of date: run node scripts/gen-opengrants.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(outPath, code);
    console.log(`wrote ${outPath}`);
  }
}
